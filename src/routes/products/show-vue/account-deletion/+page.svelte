<article>
  <h1>Account Deletion Guide</h1>
  
  <div class="warning-box">
    <h2>⚠️ Important Notice</h2>
    <p><strong>Account deletion is permanent and cannot be undone.</strong> All your personal data will be permanently removed from ShowVue. Please read this guide carefully before proceeding.</p>
  </div>

  <hr>

  <h2>What Gets Deleted</h2>
  <p>When you delete your account, the following information will be <strong>permanently removed</strong>:</p>
  <ul>
    <li>✅ <strong>Personal Profile</strong>: Name, email, contact information, profile picture, bio</li>
    <li>✅ <strong>Login Information</strong>: Password, login sessions, connected social accounts</li>
    <li>✅ <strong>Notification Preferences</strong>: Email and push notification settings</li>
    <li>✅ <strong>Uploaded Files</strong>: Profile pictures, documents, and uploaded files</li>
  </ul>

  <h2>What Remains (Anonymized)</h2>
  <p>To preserve show history, some information will remain but be <strong>anonymized</strong>:</p>
  <ul>
    <li>📋 <strong>Show Participation Records</strong>: Your roles in shows remain for historical records, but your name is replaced with "User account deleted"</li>
    <li>🎭 <strong>Show and Event Data</strong>: Shows, events, and performance information remain intact for other users</li>
  </ul>

  <hr>

  <h2>Step-by-Step Instructions</h2>

  <h3>Step 1: Request Account Deletion</h3>
  <ol>
    <li><strong>Log in</strong> to your ShowVue account</li>
    <li>Go to <strong>Account Settings</strong></li>
    <li>Scroll down to the <strong>"Delete Account"</strong> section</li>
    <li>Click <strong>"Delete My Account"</strong> button</li>
    <li>In the confirmation dialog, type <strong>"DELETE"</strong> exactly as shown</li>
    <li>Click <strong>"Send Deletion Email"</strong></li>
  </ol>
  <blockquote>
    <p><strong>Note</strong>: You must be logged in to request account deletion.</p>
  </blockquote>

  <h3>Step 2: Check Your Email</h3>
  <ol>
    <li>Check your <strong>email inbox</strong> for a message from ShowVue</li>
    <li>Look for subject: <strong>"Account Deletion Confirmation"</strong></li>
    <li>If you don't see it, <strong>check your spam/junk folder</strong></li>
    <li>The email contains a <strong>secure deletion link</strong></li>
  </ol>
  <blockquote>
    <p><strong>⏰ Important</strong>: The deletion link expires after <strong>24 hours</strong> for security.</p>
  </blockquote>

  <h3>Step 3: Confirm Final Deletion</h3>
  <ol>
    <li><strong>Click the deletion link</strong> in your email</li>
    <li>You'll be taken to a <strong>confirmation page</strong></li>
    <li><strong>Review the list</strong> of data that will be deleted</li>
    <li>Type <strong>"DELETE"</strong> in the confirmation field</li>
    <li>Click <strong>"Permanently Delete Account"</strong></li>
  </ol>
  <blockquote>
    <p><strong>🚨 Final Warning</strong>: After clicking this button, your account cannot be recovered.</p>
  </blockquote>

  <h3>Step 4: Account Deleted</h3>
  <ol>
    <li>You'll see a <strong>confirmation message</strong></li>
    <li>You'll be <strong>automatically logged out</strong></li>
    <li>All your personal data has been <strong>permanently removed</strong></li>
    <li>You can <strong>no longer log in</strong> with your old credentials</li>
  </ol>

  <hr>

  <h2>Troubleshooting</h2>

  <h3>I didn't receive the deletion email</h3>
  <ul>
    <li>Check your <strong>spam/junk folder</strong> first</li>
    <li>Try <strong>requesting deletion again</strong> from account settings</li>
    <li>Make sure your <strong>email address is correct</strong> in your profile</li>
  </ul>

  <h3>The deletion link says it's expired or invalid</h3>
  <ul>
    <li>Deletion links expire after <strong>24 hours</strong> for security</li>
    <li>Go back to <strong>account settings</strong> and request a <strong>new deletion email</strong></li>
    <li>Each link can only be used <strong>once</strong></li>
  </ul>

  <h3>I can't access my account to request deletion</h3>
  <ul>
    <li>Use the <strong>'Forgot Password'</strong> link on the login page first</li>
    <li>If you no longer have access to your email, <strong>contact support</strong></li>
  </ul>

  <h3>I changed my mind after requesting deletion</h3>
  <ul>
    <li>Simply <strong>don't click the deletion link</strong> in your email</li>
    <li>The link will <strong>expire after 24 hours</strong> and your account will remain active</li>
    <li>You can <strong>safely ignore</strong> the email</li>
  </ul>

  <h3>I accidentally deleted my account</h3>
  <ul>
    <li>Unfortunately, <strong>account deletion cannot be undone</strong></li>
    <li>All your data has been <strong>permanently removed</strong></li>
    <li>To use ShowVue again, you'll need to <strong>create a new account</strong></li>
  </ul>

  <hr>

  <h2>Alternatives to Account Deletion</h2>
  <p>Before deleting your account, consider these alternatives:</p>
  <ul>
    <li>👁️ <strong>Deactivate Account</strong>: Temporarily disable your account while keeping your data safe (contact support)</li>
    <li>🔧 <strong>Update Privacy Settings</strong>: Adjust what information is visible to other users</li>
    <li>🔕 <strong>Disable Notifications</strong>: Turn off all email and push notifications in your settings</li>
  </ul>

